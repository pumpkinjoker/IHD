import { expect, test } from "@playwright/test";
import masterData from "../../src/data/master-data.json";

test("persists an employee, a draft and a photo and restores them after refresh", async ({ page }) => {
  test.skip(process.env.IHD_RUN_LOCAL_PERSISTENCE_E2E !== "1", "Opt-in only; use an isolated local database.");
  const storageCheck = await page.request.get("/api/line/records?export=1");
  test.skip(storageCheck.status() !== 200, "Persistence fixtures must never be written into Supabase.");
  const response = await page.goto("/line/local-test");
  test.skip(response?.status() === 404, "Local persistence testing requires a development server in local mode.");
  await expect(page.getByRole("heading", { name: /ทดสอบ LINE (พร้อมบันทึกลงเครื่อง|กับ Supabase)/ })).toBeVisible();
  const cloud = await page.getByRole("heading", { name: "ทดสอบ LINE กับ Supabase", exact: true }).count();
  const entryLabel = cloud ? "รายการที่บันทึกใน Supabase" : "รายการที่บันทึกลงเครื่อง";
  await expect(page.getByRole("status")).toHaveCount(0);
  if (await page.getByRole("button", { name: "ยกเลิก", exact: true }).count()) await page.getByRole("button", { name: "ยกเลิก", exact: true }).click();
  if (await page.getByRole("button", { name: "เปลี่ยนรหัสพนักงาน", exact: true }).count()) {
    await page.getByRole("button", { name: "เปลี่ยนรหัสพนักงาน", exact: true }).click();
  } else await page.getByRole("button", { name: "เพิ่มข้อมูลหน้างาน", exact: true }).click();
  const employee = masterData.teams[0].members[0];
  const heading = page.getByRole("heading", { name: new RegExp(entryLabel) });
  const count = Number((await heading.innerText()).match(/\((\d+)\)/)![1]);
  await page.getByRole("textbox", { name: "ข้อความถึงบอต" }).fill(employee.employeeId);
  await page.getByRole("button", { name: "ส่ง", exact: true }).click();
  await page.getByRole("button", { name: "ใช่ เป็นข้อมูลของฉัน", exact: true }).click();
  await page.getByLabel("ถ่ายหรือเลือกรูปหน้างาน 1 รูป").setInputFiles("public/brand/toa-logo.png");
  await expect(page.getByText("งานนี้หัวข้ออะไรครับ?", { exact: false }).last()).toBeVisible();
  const title = `ทดสอบเก็บลงเครื่อง ${Date.now()}`;
  await page.getByRole("textbox", { name: "ข้อความถึงบอต" }).fill(title);
  await page.getByRole("button", { name: "ส่ง", exact: true }).click();
  await expect(page.getByText("สถานที่ปฏิบัติงานที่ไหนครับ?", { exact: true }).last()).toBeVisible();
  await page.reload();
  await expect(page.getByRole("status")).toHaveCount(0);
  await expect(page.getByRole("img", { name: "รูปหน้างานที่เลือก", exact: true })).toBeVisible();
  await page.getByRole("textbox", { name: "ข้อความถึงบอต" }).fill("สถานที่ทดสอบในเครื่อง");
  await page.getByRole("button", { name: "ส่ง", exact: true }).click();
  await page.getByRole("button", { name: "ใช้แล้วข้อมูลถูกต้องเวรี่กู้ด", exact: true }).click();
  await expect(heading).toHaveText(`${entryLabel} (${count + 1})`);
  await page.reload();
  await expect(heading).toHaveText(`${entryLabel} (${count + 1})`);
  const entry = page.getByRole("article").filter({ hasText: title });
  await expect(entry).toHaveCount(1);
  await expect(entry.getByText(`ผู้ปฏิบัติงาน: ${employee.name} (${employee.employeeId})`)).toBeVisible();
  await expect(entry.getByRole("img")).toBeVisible();
  await expect.poll(() => entry.getByRole("img").evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true);
  await expect(page.getByLabel("ถ่ายหรือเลือกรูปหน้างาน 1 รูป")).toBeVisible();
  await page.goto("/line/records");
  await expect(page.getByRole("heading", { name: "รายการหน้างานที่บันทึกจาก LINE", exact: true })).toBeVisible();
  await expect(page.getByRole("status")).toHaveCount(0);
  await page.getByLabel("พนักงาน", { exact: true }).selectOption(employee.employeeId);
  const saved = page.getByRole("article").filter({ hasText: title });
  await expect(saved).toHaveCount(1);
  await expect(saved.getByRole("img")).toBeVisible();
  await expect.poll(() => saved.getByRole("img").evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true);
});
